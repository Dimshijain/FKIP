-- FINXSYSTEMS CORE BANKING ORACLE SQL DDL SCHEMA
-- =========================================================

-- 1. CUSTOMERS TABLE
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER(10) PRIMARY KEY,
    FIRST_NAME VARCHAR2(50) NOT NULL,
    LAST_NAME VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PHONE_NUMBER VARCHAR2(20),
    KYC_STATUS VARCHAR2(20) DEFAULT 'VERIFIED',
    RISK_RATING VARCHAR2(10) DEFAULT 'LOW',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. ACCOUNTS TABLE
CREATE TABLE ACCOUNTS (
    ACCOUNT_ID NUMBER(12) PRIMARY KEY,
    CUSTOMER_ID NUMBER(10) NOT NULL,
    ACCOUNT_NUMBER VARCHAR2(20) UNIQUE NOT NULL,
    ACCOUNT_TYPE VARCHAR2(20) NOT NULL,
    CURRENCY VARCHAR2(3) DEFAULT 'USD',
    CURRENT_BALANCE NUMBER(15,2) DEFAULT 0.00,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT FK_ACC_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID)
);

-- 3. TRANSACTIONS TABLE
CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID NUMBER(15) PRIMARY KEY,
    ACCOUNT_ID NUMBER(12) NOT NULL,
    TRANSACTION_TYPE VARCHAR2(20) NOT NULL,
    AMOUNT NUMBER(15,2) NOT NULL,
    CHANNEL VARCHAR2(20) DEFAULT 'ONLINE',
    STATUS VARCHAR2(20) DEFAULT 'COMPLETED',
    TRANSACTION_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TXN_ACC FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS(ACCOUNT_ID)
);

-- 4. CARDS TABLE
CREATE TABLE CARDS (
    CARD_ID NUMBER(12) PRIMARY KEY,
    ACCOUNT_ID NUMBER(12) NOT NULL,
    CARD_NUMBER_TOKEN VARCHAR2(30) NOT NULL,
    CARD_TYPE VARCHAR2(20) NOT NULL,
    DAILY_LIMIT NUMBER(10,2) DEFAULT 1000.00,
    IS_FROZEN NUMBER(1) DEFAULT 0,
    EXPIRATION_DATE DATE NOT NULL,
    CONSTRAINT FK_CARD_ACC FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS(ACCOUNT_ID)
);

-- 5. LOANS TABLE
CREATE TABLE LOANS (
    LOAN_ID NUMBER(10) PRIMARY KEY,
    CUSTOMER_ID NUMBER(10) NOT NULL,
    PRINCIPAL_AMOUNT NUMBER(15,2) NOT NULL,
    INTEREST_RATE NUMBER(5,2) NOT NULL,
    LOAN_STATUS VARCHAR2(20) DEFAULT 'APPROVED',
    START_DATE DATE NOT NULL,
    CONSTRAINT FK_LOAN_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID)
);

-- 6. VIEW: CUST_ACCOUNT_SUMMARY
CREATE VIEW CUST_ACCOUNT_SUMMARY AS
SELECT 
    c.CUSTOMER_ID,
    c.FIRST_NAME || ' ' || c.LAST_NAME AS FULL_NAME,
    c.EMAIL,
    COUNT(a.ACCOUNT_ID) AS TOTAL_ACCOUNTS,
    SUM(a.CURRENT_BALANCE) AS TOTAL_BALANCE
FROM CUSTOMERS c
LEFT JOIN ACCOUNTS a ON c.CUSTOMER_ID = a.CUSTOMER_ID
GROUP BY c.CUSTOMER_ID, c.FIRST_NAME, c.LAST_NAME, c.EMAIL;

-- 7. VIEW: DAILY_TXN_TOTALS
CREATE VIEW DAILY_TXN_TOTALS AS
SELECT 
    a.ACCOUNT_ID,
    a.ACCOUNT_NUMBER,
    SUM(t.AMOUNT) AS TOTAL_DAILY_AMOUNT,
    COUNT(t.TRANSACTION_ID) AS TXN_COUNT
FROM ACCOUNTS a
JOIN TRANSACTIONS t ON a.ACCOUNT_ID = t.ACCOUNT_ID
GROUP BY a.ACCOUNT_ID, a.ACCOUNT_NUMBER;

-- 8. TRIGGER: AUDIT_TXN_LOGS
CREATE OR REPLACE TRIGGER AUDIT_TXN_LOGS
AFTER INSERT ON TRANSACTIONS
FOR EACH ROW
BEGIN
    INSERT INTO TRANSACTIONS (ACCOUNT_ID, TRANSACTION_TYPE, AMOUNT) 
    VALUES (:NEW.ACCOUNT_ID, 'AUDIT_LOG', :NEW.AMOUNT);
END;
