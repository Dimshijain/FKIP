-- ========================================================
-- FKIP Demo Database Schema: Human Resources (HR)
-- Used for parsing views, foreign keys, triggers, and impact analysis
-- ========================================================

CREATE TABLE REGIONS (
    REGION_ID NUMBER PRIMARY KEY,
    REGION_NAME VARCHAR2(25) NOT NULL
);

CREATE TABLE COUNTRIES (
    COUNTRY_ID CHAR(2) PRIMARY KEY,
    COUNTRY_NAME VARCHAR2(40),
    REGION_ID NUMBER REFERENCES REGIONS(REGION_ID)
);

CREATE TABLE LOCATIONS (
    LOCATION_ID NUMBER PRIMARY KEY,
    STREET_ADDRESS VARCHAR2(40),
    POSTAL_CODE VARCHAR2(12),
    CITY VARCHAR2(30) NOT NULL,
    STATE_PROVINCE VARCHAR2(25),
    COUNTRY_ID CHAR(2) REFERENCES COUNTRIES(COUNTRY_ID)
);

CREATE TABLE DEPARTMENTS (
    DEPARTMENT_ID NUMBER PRIMARY KEY,
    DEPARTMENT_NAME VARCHAR2(30) NOT NULL,
    MANAGER_ID NUMBER,
    LOCATION_ID NUMBER REFERENCES LOCATIONS(LOCATION_ID)
);

CREATE TABLE JOBS (
    JOB_ID VARCHAR2(10) PRIMARY KEY,
    JOB_TITLE VARCHAR2(35) NOT NULL,
    MIN_SALARY NUMBER(6),
    MAX_SALARY NUMBER(6)
);

CREATE TABLE EMPLOYEES (
    EMPLOYEE_ID NUMBER PRIMARY KEY,
    FIRST_NAME VARCHAR2(20),
    LAST_NAME VARCHAR2(25) NOT NULL,
    EMAIL VARCHAR2(25) UNIQUE NOT NULL,
    PHONE_NUMBER VARCHAR2(20),
    HIRE_DATE DATE NOT NULL,
    JOB_ID VARCHAR2(10) REFERENCES JOBS(JOB_ID),
    SALARY NUMBER(8,2),
    COMMISSION_PCT NUMBER(2,2),
    MANAGER_ID NUMBER REFERENCES EMPLOYEES(EMPLOYEE_ID),
    DEPARTMENT_ID NUMBER REFERENCES DEPARTMENTS(DEPARTMENT_ID)
);

-- Join view detailing employee allocations
CREATE VIEW EMP_DETAILS_VIEW AS
SELECT 
    E.EMPLOYEE_ID, 
    E.FIRST_NAME, 
    E.LAST_NAME, 
    E.EMAIL, 
    D.DEPARTMENT_NAME, 
    J.JOB_TITLE, 
    L.CITY
FROM EMPLOYEES E
JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN JOBS J ON E.JOB_ID = J.JOB_ID
JOIN LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID;

-- Audit trigger log on employee updates
CREATE TRIGGER SECURE_EMPLOYEES
BEFORE INSERT OR UPDATE OR DELETE ON EMPLOYEES
FOR EACH ROW
BEGIN
    INSERT INTO AUDIT_LOG (LOG_DATE, USER_ID, ACTION_TYPE)
    VALUES (SYSDATE, USER, 'EMPLOYEE_MODIFICATION');
END;
